import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import * as THREE from '../vendor/three.module.js';
import { GLTFLoader } from '../vendor/GLTFLoader.js';
import { assemblePhone, SCREEN } from '../phone-model.js';

// Geometry test only: stub image decoding because this is not a WebGL/browser test.
globalThis.self = globalThis;
globalThis.createImageBitmap = async () => ({ width: 1, height: 1, close() {} });
if (!globalThis.ProgressEvent) globalThis.ProgressEvent = class { constructor(type, data) { Object.assign(this, { type }, data); } };
const buffer = await readFile(new URL('../assets/galaxy-z-flip-7.glb', import.meta.url));
const gltf = await new GLTFLoader().parseAsync(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength), '');
const phone = assemblePhone(gltf);
assert.equal(phone.root.children.length, 1, 'Only one phone copy is rendered');
assert.equal(phone.top.parent, phone.hinge, 'The top half must rotate with the hinge');
assert.equal(phone.bottom.parent, phone.body, 'The bottom half remains stationary');
phone.root.updateMatrixWorld(true);
const bounds = new THREE.Box3().setFromObject(phone.root);
const size = bounds.getSize(new THREE.Vector3());
assert(size.x > 1.9 && size.x < 2.1, 'Open phone width is approximately 75 mm × 26');
assert(size.y > 4.3 && size.y < 4.4, 'Open phone height is approximately 167 mm × 26');
const screen = new THREE.Vector3(0, 0.075, SCREEN.z);
const cover = new THREE.Object3D();
cover.position.set(0, 0.0305, -0.00365);
cover.rotation.x = Math.PI;
phone.top.add(cover);
const openPoint = phone.top.localToWorld(screen.clone());
const bottomOpen = new THREE.Box3().setFromObject(phone.bottom);
phone.hinge.rotation.x = Math.PI;
phone.root.updateMatrixWorld(true);
const foldedPoint = phone.top.localToWorld(screen.clone());
const bottomFolded = new THREE.Box3().setFromObject(phone.bottom);
assert(openPoint.y > 1.8 && foldedPoint.y < -1.8, 'Top folds across the hinge onto the bottom half');
assert(foldedPoint.z > 0.09, 'Folded interior screen stays in front of the bottom screen');
const coverRotation = cover.getWorldQuaternion(new THREE.Quaternion());
assert(new THREE.Vector3(0, 1, 0).applyQuaternion(coverRotation).y > 0.99, 'Folded cover screen text remains upright');
assert(new THREE.Vector3(0, 0, 1).applyQuaternion(coverRotation).z > 0.99, 'Folded cover screen faces the camera');
assert(bottomOpen.equals(bottomFolded), 'Folding does not move the bottom half');
const foldedSize = new THREE.Box3().setFromObject(phone.root).getSize(new THREE.Vector3());
assert(foldedSize.y < size.y * 0.53, 'Folded phone has half the height');
assert(SCREEN.width / 232 * 540 - SCREEN.height < 0.00005, 'DOM screen aspect ratio fits the GLB');
phone.hinge.rotation.x = 0;
phone.root.updateMatrixWorld(true);
assert(phone.top.localToWorld(screen.clone()).distanceTo(openPoint) < 1e-6, 'Reopening restores the original geometry');
console.log('GLB loads; one articulated phone; screen proportions and open/fold/reopen geometry verified.');
